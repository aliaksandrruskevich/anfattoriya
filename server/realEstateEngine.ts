/**
 * Helper to match subdistrict to key district
 */
function findDistrictByQuery(text: string): { key: string; details: DistrictDetails; matchedSub: string } | null {
  const q = text.toLowerCase();
  for (const [key, details] of Object.entries(MINSK_DISTRICTS)) {
    for (const sub of details.subDistricts) {
      if (q.includes(sub)) {
        return { key, details, matchedSub: sub };
      }
    }
  }
  // Check main district names
  if (q.includes('фрунзенск')) return { key: 'frunzensky', details: MINSK_DISTRICTS.frunzensky, matchedSub: 'Фрунзенский район' };
  if (q.includes('октябрьск')) return { key: 'octyabrsky', details: MINSK_DISTRICTS.octyabrsky, matchedSub: 'Октябрьский район' };
  if (q.includes('центральн')) return { key: 'center', details: MINSK_DISTRICTS.center, matchedSub: 'Центральный район' };
  if (q.includes('первомайск')) return { key: 'pervomaysky', details: MINSK_DISTRICTS.pervomaysky, matchedSub: 'Первомайский район' };
  if (q.includes('советск')) return { key: 'sovetsky', details: MINSK_DISTRICTS.sovetsky, matchedSub: 'Советский район' };
  if (q.includes('московск')) return { key: 'moskovsky', details: MINSK_DISTRICTS.moskovsky, matchedSub: 'Московский район' };
  if (q.includes('ленинск')) return { key: 'leninsky', details: MINSK_DISTRICTS.leninsky, matchedSub: 'Ленинский район' };
  if (q.includes('партизанск')) return { key: 'partizansky', details: MINSK_DISTRICTS.partizansky, matchedSub: 'Партизанский район' };
  if (q.includes('заводск')) return { key: 'zavodskoy', details: MINSK_DISTRICTS.zavodskoy, matchedSub: 'Заводской район' };

  return null;
}

