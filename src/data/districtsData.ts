export function getDistrictBySlug(slug: string): DistrictInfo | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().replace(/^\/+|\/+$/g, '').replace(/^(kupit-kvartiru-|kupit-kvartiru\/|rajon-)/, '');
  return MINSK_DISTRICTS_DATA.find(d => d.slug === clean || d.id === clean || d.slug.includes(clean));
}

