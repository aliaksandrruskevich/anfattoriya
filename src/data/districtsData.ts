/**
 * High-accuracy matcher that matches a property to a district info record.
 * Handles both explicit district fields, address keywords, metro stations, and title tags.
 * Strictly verifies that the object belongs to Minsk / Minsk District and excludes foreign locations.
 */
export function matchPropertyToDistrict(property: any, district: DistrictInfo): boolean {
  if (!property || !district) return false;

  const pDistrict = (property.district || '').toLowerCase();
  const pAddress = (property.address || property.location || '').toLowerCase();
  const pTitle = (property.title || '').toLowerCase();
  const pDesc = (property.description || '').toLowerCase();
  const pMetro = (property.metro || '').toLowerCase();
  const pFeatures = Array.isArray(property.features) ? property.features.join(' ').toLowerCase() : '';

  const fullText = `${pDistrict} ${pAddress} ${pTitle} ${pDesc} ${pMetro} ${pFeatures}`.toLowerCase();

  // Strict check: if the property is located in another city (e.g., Ostrovets), reject immediately
  const hasNonMinskLocation = NON_MINSK_LOCATIONS.some(loc => {
    // Only flag if the word appears distinctly and isn't part of a Minsk street name
    const regex = new RegExp(`(^|[^а-яёa-z])${loc}([^а-яёa-z]|$)`, 'i');
    return regex.test(pAddress) || regex.test(pTitle) || regex.test(pDistrict);
  });

  if (hasNonMinskLocation) {
    return false;
  }

  // 1. Direct name match (e.g. "Первомайский", "Первомайский район")
  const districtPureName = district.name.toLowerCase().replace(' район', '').replace('микрорайон ', '').replace('жк ', '').trim();
  if (pDistrict && (pDistrict.includes(districtPureName) || pDistrict === district.name.toLowerCase())) {
    return true;
  }

  // 2. Specific check for sub-districts / complexes
  if (district.id === 'minsk-mir') {
    return fullText.includes('минск-мир') || fullText.includes('минск мир') || fullText.includes('minsk world') || fullText.includes('братская') || fullText.includes('николы теслы') || fullText.includes('белградская') || fullText.includes('аэродромная');
  }
  if (district.id === 'novaya-borovaya') {
    return fullText.includes('новая боровая') || fullText.includes('копище') || fullText.includes('авиационная');
  }
  if (district.id === 'uruchie') {
    return fullText.includes('уручь') || fullText.includes('руссиянова') || fullText.includes('никифорова') || fullText.includes('шафарнянск');
  }
  if (district.id === 'lebyazhij') {
    return fullText.includes('лебяж') || fullText.includes('ратомская') || fullText.includes('мястровская') || fullText.includes('нарочанская') || fullText.includes('олимпик парк');
  }

  // 3. Match against district keywords list
  if (district.keywords && district.keywords.length > 0) {
    const hasKeyword = district.keywords.some(kw => fullText.includes(kw.toLowerCase()));
    if (hasKeyword) return true;
  }

  // 4. Match against metro stations of the district
  if (district.metroStations && district.metroStations.length > 0) {
    const hasMetro = district.metroStations.some(st => {
      // Exclude generic word matches like '10 мин'
      if (st.includes('мин')) return false;
      return fullText.includes(st.toLowerCase());
    });
    if (hasMetro) return true;
  }

  // 5. Fallback searchFilter
  if (district.searchFilter && fullText.includes(district.searchFilter.toLowerCase())) {
    return true;
  }

  return false;
}

/**
 * Determines the primary district name for any property
 */
export function resolveDistrictName(property: any): string {
  if (!property) return 'Минск';
  if (property.district && property.district.trim().length > 1 && property.district !== 'Минск') {
    return property.district;
  }

  for (const d of MINSK_DISTRICTS_DATA) {
    if (matchPropertyToDistrict(property, d)) {
      return d.name;
    }
  }

  return 'Центральный район';
}
